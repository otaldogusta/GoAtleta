"""Retarget CMU 16_35 to the court armature and key the P1 arm drive.

Run in Blender after author-court-skill-clips.py. Source and export coordinates
are local metres facing +Z, with phase zero at right-foot contact. The editor
owns travel, the cut and the planted marks. The .blend retains its IK controls.
"""
import json
import math
from pathlib import Path

import bpy
from mathutils import Matrix, Vector


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / ".tmp" / "volleyball-v2"
MODULES = ROOT / "public" / "visual-court-3d"
source = (MODULES / "reception-run-clip.mjs").read_text(encoding="utf-8")
rows = json.loads(source.split(" = ", 1)[1].strip().rstrip(";").replace(",\n]", "\n]"))


def to_blender(v):
    return Vector((v.x, -v.z, v.y))


def from_blender(v):
    return (v.x, v.z, -v.y)


def pose_controls(row):
    points = [Vector(row[i:i+3]) * .001 for i in range(0, len(row), 3)]
    hips, chest, head = points[:3]
    # The mocap actor jogs almost upright. Lean the shirt from the hips and
    # let the neck absorb part of that pitch so the setter still sees the pass.
    trunk = Matrix.Rotation(math.radians(13), 3, "X")
    root = Vector((0, hips.y+.043, 0))
    sternum = root + trunk @ ((chest-hips).normalized() * .51)
    skull = sternum + (head-chest).normalized() * .235
    goals = {"hips":root, "chest":sternum, "skull":skull}
    for i, side in enumerate("LR"):
        sign = -1 if i == 0 else 1
        sh, el, palm, hip, knee, ankle, toe = points[3+7*i:10+7*i]
        # Keep the timing of the recorded contralateral arm swing. Scale its
        # small excursion into a shoulder drive for a short accelerating run.
        upper_swing = math.atan2(el.z-sh.z, sh.y-el.y)
        swing = max(-1, min(1, (upper_swing+math.radians(33))/math.radians(14)))
        # The elbow drives behind the ribs; the forward hand comes up toward
        # the chest as the elbow folds, instead of reaching out at waist level.
        upper_angle = math.radians(-29+23*swing)
        lower_angle = upper_angle + math.radians(104+24*swing)
        shoulder = sternum + trunk @ (sh-chest)
        elbow = shoulder + Vector((sign*.13, -math.cos(upper_angle), math.sin(upper_angle))).normalized()*.352
        wrist = elbow + Vector((-sign*.15, -math.cos(lower_angle), math.sin(lower_angle))).normalized()*.382
        hip_joint = root + hip-hips
        knee_goal = hip_joint + (knee-hip).normalized()*.454
        ankle_goal = knee_goal + (ankle-knee).normalized()*.451
        goals.update({
            "hip"+side:hip_joint, "kneePole"+side:knee_goal, "ankle"+side:ankle_goal,
            "toe"+side:ankle_goal + (toe-ankle).normalized()*.19,
            "shoulder"+side:shoulder, "palm"+side:wrist, "elbowPole"+side:elbow,
            "fingerGoal"+side:wrist + (wrist-elbow).normalized()*.092,
        })
    return goals


bpy.ops.wm.open_mainfile(filepath=str(OUT / "Go Atleta - Gestos com bola.blend"))
scene = bpy.context.scene
rig = next(obj for obj in scene.objects if obj.type == "ARMATURE")
action = bpy.data.actions.new("Infiltração do levantador · P1")
rig.animation_data.action = action
rig.location = (0, 0, 0)
rig.pose.bones["bola"].location = (0, 0, -10)
for frame, row in enumerate(rows, 1):
    for name, position in pose_controls(row).items():
        ctl = rig.pose.bones["ctl."+name]
        ctl.location = to_blender(position) - ctl.bone.head_local
        ctl.keyframe_insert("location", frame=frame, group=name)
for curve in action.fcurves:
    for key in curve.keyframe_points:
        key.interpolation = "BEZIER"
        key.handle_left_type = key.handle_right_type = "AUTO_CLAMPED"
for frame, name in [(1,"Apoio direito"),(27,"Apoio esquerdo"),(52,"Apoio direito")]:
    action.pose_markers.new(name).frame = frame
action.use_fake_user = True
action.asset_mark()
scene.frame_start, scene.frame_end = 1, len(rows)
scene.render.fps = 60
export = []
for frame in range(1,len(rows)+1):
    scene.frame_set(frame)
    bones = rig.evaluated_get(bpy.context.evaluated_depsgraph_get()).pose.bones
    points = [bones["ctl."+name].head for name in ("hips","chest","skull")]
    for side in "LR":
        points.extend(bones[name+side].head for name in ("arm","forearm","hand","thigh","shin","foot"))
        points.append(bones["foot"+side].tail)
    export.append([round(m*1000) for p in points for m in from_blender(p)])
assert export[0] == export[-1]
module = MODULES / "setter-run-data.mjs"
module.write_bytes(("// Generated by scripts/author-court-setter-run.py. Local XYZ in mm.\n"
                    +"export const setterRunPoses = [\n"
                    +"".join("  ["+",".join(map(str,row))+"],\n" for row in export)+"];\n").encode("utf-8"))
scene.frame_set(6)
bpy.context.preferences.filepaths.save_version = 0
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/"Go Atleta - Corrida do levantador.blend"))
