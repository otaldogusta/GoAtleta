import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const org = '20000000-0000-0000-0000-000000000001';
const other = '20000000-0000-0000-0000-000000000002';
const admin = '10000000-0000-0000-0000-000000000001';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key); insert into auth.users values ('${admin}');
    create function auth.uid() returns uuid language sql as 'select nullif(current_setting(''request.jwt.claim.sub'',true),'''')::uuid';
    create table organizations(id uuid primary key); insert into organizations values ('${org}'),('${other}');
    create function public.is_org_admin(id uuid) returns boolean language sql as 'select auth.uid() = ''${admin}''::uuid and id = ''${org}''::uuid';
    create table classes(id text primary key, organization_id uuid, days jsonb);
    insert into classes values ('a','${org}','[1]'),('b','${org}','[1]'),('foreign','${other}','[1]'),('tuesday','${org}','[2]');
    create table class_calendar_exceptions(id text primary key,class_id text,organization_id uuid,date date,reason text,kind text, unique(class_id,date,kind));
    insert into class_calendar_exceptions values ('manual','a','${org}','2026-09-07','Viagem','no_training');
    grant usage on schema public,auth to authenticated,anon;
  `);
  const sql = await readFile(new URL('../../supabase/migrations/20260907234850_organization_activity_reviews.sql', import.meta.url), 'utf8');
  await db.exec(sql.replaceAll("(now() at time zone 'America/Sao_Paulo')::date", "date '2026-09-07'"));
  await db.exec(`create table events(id uuid primary key default gen_random_uuid(),organization_id uuid,title text,description text,event_type text,sport text,starts_at timestamptz,ends_at timestamptz,all_day boolean,created_by uuid); create table event_classes(event_id uuid,organization_id uuid,class_id text,primary key(event_id,class_id));`);
  const extension = await readFile(new URL('../../supabase/migrations/20260908032524_activity_review_details.sql', import.meta.url), 'utf8');
  await db.exec(extension.replaceAll("(now() at time zone 'America/Sao_Paulo')::date", "date '2026-09-07'"));
  const detailed = (reason, note='', resolution=null, newDate=null, ids=['b'], start='2026-08-24', end=start) => db.query('select review_organization_activity_details($1,$2::text[],$3,$4,$5,$6,$7,$8)',[org,ids,start,end,reason,note,resolution,newDate]);
  const call = (ids,reason='recess',organization=org,start='2026-08-31',end='2026-09-07') => db.query('select review_organization_activity($1,$2::text[],$3,$4,$5)',[organization,ids,start,end,reason]);
  await db.exec('set role authenticated');
  await assert.rejects(()=>call(['a']),/Not authorized/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[admin]);
  await assert.rejects(()=>call(['foreign']),/Invalid class/);
  await assert.rejects(()=>call([]),/Invalid class/);
  await assert.rejects(()=>call(['a'],'recess',other),/Not authorized/);
  await assert.rejects(()=>call(['a'],'invalid'),/Invalid review/);
  await assert.rejects(()=>call(['a'],'recess',org,'2026-01-01','2026-09-07'),/Invalid review/);
  await call(['b','a']); await call(['a','b']);
  assert.equal((await db.query('select * from organization_activity_reviews')).rows.length,1);
  await assert.rejects(()=>db.exec('delete from organization_activity_reviews'),/permission denied/);
  await db.exec('reset role');
  const rows=(await db.query('select * from class_calendar_exceptions')).rows;
  assert.equal(rows.length,4);
  assert.equal(rows.find(r=>r.id==='manual').reason,'Viagem');
  await db.exec('set role authenticated');
  await call(['a'],'held');
  await db.exec('reset role');
  assert.equal((await db.query('select * from class_calendar_exceptions')).rows.length,4);
  await db.exec('set role authenticated');
  await assert.rejects(()=>detailed('other'),/Describe the reason/);
  await assert.rejects(()=>detailed('tournament'),/Choose event resolution/);
  await assert.rejects(()=>detailed('tournament','','rescheduled','2026-08-23'),/Invalid reschedule/);
  await assert.rejects(()=>detailed('holiday','',null,null,['foreign']),/Invalid class/);
  await assert.rejects(()=>detailed('tournament','','rescheduled','2026-09-15',['b'],'2026-08-24','2026-08-31'),/Invalid reschedule/);
  await detailed('tournament','','rescheduled','2026-09-15');
  await detailed('tournament','','rescheduled','2026-09-15');
  await assert.rejects(()=>detailed('tournament','','rescheduled','2026-09-16'),/different review/);
  await detailed('other','Quadra interditada',null,null,['a']);
  await db.exec('reset role');
  assert.equal((await db.query('select * from events')).rows.length,1);
  assert.equal((await db.query('select * from event_classes')).rows[0].class_id,'b');
  assert.match((await db.query("select reason from class_calendar_exceptions where class_id='a' and date='2026-08-24'")).rows[0].reason,/Quadra interditada/);
  await db.exec('set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub','',false)");
  assert.equal((await db.query('select * from organization_activity_reviews')).rows.length,0);
  console.log('Activity review SQL passed: authorization, scope, bounds, idempotency, scheduled days, preserved pauses and held classes.');
} finally { await db.close(); }
