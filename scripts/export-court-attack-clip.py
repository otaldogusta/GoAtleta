"""Export the edited Blender spike to the court's local joint coordinates.

blender -b swing.blend --disable-autoexec --python-exit-code 1 \
  --python scripts/export-court-attack-clip.py -- public/visual-court-3d/attack-captured-positions.mjs \
  src/core/court-simulation/attack-approach-data.js

The second path is optional and writes the two ground-displacement channels
for the simulation host, without loading the browser's joint clip there.
"""

import hashlib
import json
import math
import sys
from pathlib import Path

import bpy


TAKEOFF, CONTACT, LANDING = 132, 145, 159
ANCHORS = (1, 12, 70, 104, 117, 125, 127, 130, TAKEOFF, 136, 141, 143, CONTACT, 149, LANDING, 164, 172)
SAMPLES_PER_FRAME = 32
ERROR_MM = 3.0

JOINTS = {"pelvis": "Quadril", "chest": "Peito", "head": "Cabeça"}
for side, suffix in (("left", "E"), ("right", "D")):
    for joint, obj in (
        ("Shoulder", "ombro_{}"),
        ("Elbow", "cotovelo_{} • junta visual"),
        ("Wrist", "punho_{} • junta visual"),
        ("Hand", "mao_{} • posição visual"),
        ("Hip", "quadril_{}"),
        ("Knee", "joelho_{} • junta visual"),
        ("Ankle", "tornozelo_{} • junta visual"),
        ("Heel", "calcanhar_{} • posição visual"),
        ("Toe", "ponta_pe_{} • posição visual"),
    ):
        JOINTS[side + joint] = obj.format(suffix)


def sample_scene():
    scene = bpy.context.scene
    objects = [scene.objects[name] for name in JOINTS.values()]
    root = objects[0]

    def set_time(t):
        frame = math.floor(t)
        scene.frame_set(frame, subframe=t - frame)

    if (scene.frame_start, scene.frame_end) != (ANCHORS[0], ANCHORS[-1]):
        raise ValueError("The authored timeline must span frames 1–172")
    set_time(TAKEOFF)
    takeoff_height = root.matrix_world.translation.z
    set_time(LANDING)
    landing_height = root.matrix_world.translation.z
    set_time(scene.frame_start)
    origin = root.matrix_world.translation.copy()

    samples = []
    for tick in range(scene.frame_start * SAMPLES_PER_FRAME, scene.frame_end * SAMPLES_PER_FRAME + 1):
        t = tick / SAMPLES_PER_FRAME
        set_time(t)
        hip = root.matrix_world.translation
        pose = []
        for obj in objects:
            p = obj.matrix_world.translation
            # Blender +X forward, +Y left, +Z up. The court rig labels +X right.
            pose.extend((hip.y - p.y, p.z, p.x - hip.x))
        flight = 0
        if TAKEOFF < t < LANDING:
            u = (t - TAKEOFF) / (LANDING - TAKEOFF)
            flight = max(0, hip.z - (takeoff_height + u * (landing_height - takeoff_height)))
        pose.extend((origin.y - hip.y, flight, hip.x - origin.x))
        samples.append([v * 1000 for v in pose])
    return samples


def squared_pose_error(observed, first, last, fraction):
    worst = 0
    for i in range(0, len(observed), 3):
        error = 0
        for axis in range(i, i + 3):
            delta = observed[axis] - (first[axis] + fraction * (last[axis] - first[axis]))
            error += delta * delta
        worst = max(worst, error)
    return worst


def select_keys(samples):
    # Reduce positions using the error of the actual quantized, linearly
    # interpolated runtime result, across all joints, including the fingertips.
    rounded = [[round(v) for v in pose] for pose in samples]
    keys = [(f - ANCHORS[0]) * SAMPLES_PER_FRAME for f in ANCHORS]
    work = list(zip(keys, keys[1:]))
    worst_retained = max(squared_pose_error(sample, exact, exact, 0)
                         for sample, exact in zip(samples, rounded))
    while work:
        start, end = work.pop()
        if end <= start + 1:
            continue
        error, split = max(
            (squared_pose_error(samples[i], rounded[start], rounded[end], (i - start) / (end - start)), i)
            for i in range(start + 1, end)
        )
        if error > ERROR_MM ** 2:
            keys.append(split)
            work.extend(((start, split), (split, end)))
        else:
            worst_retained = max(worst_retained, error)
    return sorted(keys), rounded, math.sqrt(worst_retained)


def write_approach(output, samples, digest):
    # The host samples the pelvis from the first approach pose through takeoff.
    # Root motion is the final XYZ triplet, after the joint landmarks.
    rows = [samples[(frame - ANCHORS[0]) * SAMPLES_PER_FRAME] for frame in range(12, TAKEOFF + 1)]
    lines = ["// Generated by scripts/export-court-attack-clip.py. Frames 12–132, millimetres.",
             f"// Source .blend SHA-256: {digest}"]
    for channel, axis in (("acrossMm", -3), ("forwardMm", -1)):
        values = [round(row[axis]) for row in rows]
        lines.append(f"export const {channel} = new Int16Array([")
        for i in range(0, len(values), 14):
            lines.append("  " + ", ".join(map(str, values[i:i + 14])) + ",")
        lines.append("]);")
    output.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


def export(output, approach_output=None):
    samples = sample_scene()
    keys, quantized, error = select_keys(samples)
    frames = [ANCHORS[0] + key / SAMPLES_PER_FRAME for key in keys]
    names = [*JOINTS, "rootMotion"]
    digest = hashlib.sha256(Path(bpy.data.filepath).read_bytes()).hexdigest()
    lines = [
        "// Generated by scripts/export-court-attack-clip.py. Units: millimetres.",
        f"// Source .blend SHA-256: {digest}",
        f"export const jointNames = {json.dumps(names)};",
        "export const frames = new Float32Array([",
    ]
    for i in range(0, len(frames), 12):
        lines.append("  " + ", ".join(f"{f:.9g}" for f in frames[i:i + 12]) + ",")
    lines.extend(("]);", "// Each row stores the millimetre change from the previous pose.",
                  "export const positions = new Int16Array(["))
    previous = [0] * (len(names) * 3)
    for key, frame in zip(keys, frames):
        pose = quantized[key]
        delta = [new - old for old, new in zip(previous, pose)]
        if any(abs(v) > 32767 for v in pose + delta):
            raise ValueError(f"Position overflow at frame {frame}")
        lines.append("  " + ",".join(map(str, delta)) + f", // {frame:.9g}")
        previous = pose
    lines.extend(("]);", "const stride = jointNames.length * 3;",
                  "for (let i = stride; i < positions.length; i++) positions[i] += positions[i - stride];"))
    output.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    if approach_output is not None:
        write_approach(approach_output, samples, digest)
    print(f"Exported {len(keys)} poses, {len(names)} XYZ channels, {len(samples)} evaluated poses; "
          f"maximum position error {error:.3f} mm.")


if __name__ == "__main__":
    destinations = sys.argv[sys.argv.index("--") + 1:]
    if not 1 <= len(destinations) <= 2:
        raise SystemExit("Expected joint-clip path and optional approach-data path")
    export(*map(Path, destinations))
