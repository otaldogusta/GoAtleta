import { createElement } from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { VideoLinkField } from '../video/VideoLinkField.web';
jest.mock('react-native', () => ({ ActivityIndicator: 'spinner' }));
jest.mock('../../../ui/app-theme', () => ({ useAppTheme: () => ({ colors: {} }) }));
jest.mock('../../../ui/icon-registry', () => ({ GoAtletaIcon: 'icon' }));
beforeEach(() => jest.useFakeTimers());
afterEach(() => jest.useRealTimers());
test('debounces edits, validates latest link and cancels on close', () => {
    const onVerify = jest.fn(), onChange = jest.fn();
    const props = { value: '', disabled: false, valid: false, error: false, onVerify, onChange };
    let view!: ReactTestRenderer;
    act(() => { view = create(createElement(VideoLinkField, props)); jest.advanceTimersByTime(500); });
    expect(onVerify).not.toHaveBeenCalled();
    act(() => view.update(createElement(VideoLinkField, { ...props, value: 'https://youtu.be/abcdefghijk' })));
    act(() => jest.advanceTimersByTime(300));
    act(() => view.update(createElement(VideoLinkField, { ...props, value: 'https://youtu.be/12345678901' })));
    act(() => jest.advanceTimersByTime(300));
    expect(onVerify).not.toHaveBeenCalled();
    act(() => jest.advanceTimersByTime(200));
    expect(onVerify).toHaveBeenCalledTimes(1);
    act(() => view.update(createElement(VideoLinkField, { ...props, value: 'invalid' })));
    act(() => view.unmount());
    act(() => jest.advanceTimersByTime(500));
    expect(onVerify).toHaveBeenCalledTimes(1);
});
test('check requires confirmation; Drive stays in its own flow', () => {
    const props = { value: 'https://drive.google.com/file/d/example/view', disabled: false, valid: false, error: false, onVerify: jest.fn(), onChange: jest.fn() };
    let view!: ReactTestRenderer;
    act(() => { view = create(createElement(VideoLinkField, props)); });
    act(() => jest.advanceTimersByTime(500));
    expect(props.onVerify).not.toHaveBeenCalled();
    expect(view.root.findAllByProps({ 'aria-label': 'Vídeo verificado' })).toHaveLength(0);
    act(() => view.update(createElement(VideoLinkField, { ...props, value: 'https://youtu.be/abcdefghijk', valid: true })));
    expect(view.root.findAllByProps({ 'aria-label': 'Vídeo verificado' })).toHaveLength(1);
    act(() => view.update(createElement(VideoLinkField, { ...props, valid: false, error: true })));
    expect(view.root.findAllByProps({ 'aria-label': 'Vídeo verificado' })).toHaveLength(0);
    act(() => view.unmount());
});
